import SOUNDS from './sounds.json' with { type: 'json' };
import { licenceTerms } from './soundManifest.js';

// The game's credits, made from the sound manifest (and a short list of the
// code libraries and art the game is built with). The CREDITS screen
// (src/ui/credits.js) and CREDITS.md (node scripts/assets/build-credits.mjs)
// both use these, so they can never disagree with the licence records.

// ---- Sounds ----

// One entry per source a shipped sound uses: who made it, its licence, the
// exact attribution text, what it is used for in the game, and whether credit
// is required (CC BY, CC BY-NC) or a courtesy (CC0).
export function soundCredits(manifest = SOUNDS) {
  // 1. Which sounds use each source (by their plain-word labels).
  const uses = new Map();
  for (const sound of manifest.sounds) {
    for (const variation of sound.variations) {
      for (const key of variation.credits ?? []) {
        if (!uses.has(key)) uses.set(key, new Set());
        uses.get(key).add(sound.label ?? soundLabel(sound.id));
      }
    }
  }
  // 2. The source records, required credits first, then by author.
  return [...uses].map(([key, ids]) => {
    const source = manifest.sources[key];
    const terms = licenceTerms(source);
    return { key, ...source, licenceUrl: terms.url, required: terms.attribution, nonCommercial: terms.nonCommercial,
      sounds: [...ids] };
  }).sort((a, b) => Number(b.required) - Number(a.required) || a.author.localeCompare(b.author) || a.title.localeCompare(b.title));
}

// A sound id in plain words, for a sound without a label ('leaperStompWindup' -> 'Leaper stomp windup').
export function soundLabel(id) {
  const words = id.replace(/([a-z0-9])([A-Z])/g, '$1 $2').toLowerCase();
  return words.charAt(0).toUpperCase() + words.slice(1).replace(/\bm416\b/, 'M416');
}

