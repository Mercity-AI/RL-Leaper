// ---- CREDITS.md ----

const markdownLink = (text, url) => (url && /^https?:/.test(url) ? `[${text}](${url})` : text);

// The whole CREDITS.md text.
export function creditsMarkdown(manifest = SOUNDS) {
  const sounds = soundCredits(manifest);
  const line = (credit) => `- ${credit.attribution}. Used for: ${credit.sounds.join(', ')}.`
    + (credit.licenceUrl ? ` Licence: ${markdownLink(credit.licence, credit.licenceUrl)}.` : '');
  const required = sounds.filter((credit) => credit.required);
  const courtesy = sounds.filter((credit) => !credit.required);
  const nonCommercial = sounds.filter((credit) => credit.nonCommercial);
  return [
    '# Credits',
    '',
    '<!-- Generated from src/audio/sounds.json by `node scripts/assets/build-credits.mjs`. Do not edit by hand. -->',
    '',
    'Leaper is a non-commercial, open-source game. These are the people and',
    'projects whose work it uses. The same list is shown in the game\'s credits.',
    '',
    '## Sounds that require credit',
    '',
    ...required.map(line),
    '',
    '## Sounds in the public domain (CC0), credited with thanks',
    '',
    ...courtesy.map(line),
    '',
    '## Licence notes',
    '',
    ...(nonCommercial.length
      ? nonCommercial.map((credit) => `- NonCommercial: "${credit.title}" by ${credit.author} (${credit.licence}) is used for ${credit.sounds.join(', ')}. That is fine for this non-commercial game; any paid, ad-supported or promotional use needs a replacement or the author's permission.`)
      : ['- No NonCommercial sounds.']),
    '- Every sound\'s source, cut and licence is recorded in `src/audio/sounds.json`; the originals are in `assets/audio/sources/`.',
    '',
    '## Code and art',
    '',
    ...PROJECT_CREDITS.map((credit) => `- ${markdownLink(credit.title, credit.sourceUrl)}: ${credit.author}`
      + `${credit.licence ? ` (${credit.licence})` : ''}${[credit.note, credit.provenance].filter(Boolean).map((text) => `, ${text}`).join('')}.`),
    '',
    'The game\'s own code has no licence chosen yet. What is known about where the',
    'character, map and Leaper came from is recorded in `assets/PROVENANCE.md`.',
    '',
  ].join('\n');
}
