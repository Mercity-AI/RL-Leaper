// Print the game's controls as a Markdown table, generated from the input
// bindings (src/input/actions.js) through the same rows the in-game legend shows
// (src/ui/ControlsLegend.js), so the README can never disagree with the game.
//
// Usage:
//   node scripts/print-controls.mjs           print the table
//   node scripts/print-controls.mjs --write   replace the table in README.md
//                                             (between the controls:start / end markers)
//   node scripts/print-controls.mjs --check   exit 1 if README.md's table is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { controlsMarkdown } from '../src/ui/ControlsLegend.js';

// The README block the table lives in.
export const START = '<!-- controls:start (generated by scripts/print-controls.mjs, do not edit by hand) -->';
export const END = '<!-- controls:end -->';
const README = fileURLToPath(new URL('../README.md', import.meta.url));

// README text with the block replaced by `table` (null when the markers are missing).
export function withTable(text, table = controlsMarkdown()) {
  const start = text.indexOf(START), end = text.indexOf(END);
  if (start < 0 || end < start) return null;
  return `${text.slice(0, start + START.length)}\n${table}\n${text.slice(end)}`;
}

// Run only when called as a script (the test imports withTable).
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const table = controlsMarkdown();
  const mode = process.argv[2] ?? '';
  if (mode === '--write' || mode === '--check') {
    const text = readFileSync(README, 'utf8');
    const next = withTable(text, table);
    if (next === null) {
      console.error(`README.md has no controls block (${START} ... ${END}).`);
      process.exit(1);
    }
    if (mode === '--check') {
      if (next !== text) {
        console.error('README.md controls table is out of date: run node scripts/print-controls.mjs --write');
        process.exit(1);
      }
      console.log('README.md controls table is up to date.');
    } else {
      writeFileSync(README, next);
      console.log('README.md controls table written.');
    }
  } else {
    console.log(table);
  }
}
